// how-to video 11 (Mike 2026-11-25): Bible reading. Listen, ◀ ▶, pick a book and chapter, mark what you've read, progress colours,
// chapters a day on the Shelf, 📖 Bible reading in Treasures. Pretend cards (Mike's banners), no jw.org pictures.
const {phone, sleep} = require('./howto-lib.js'); const fs = require('fs');
const SP = process.argv[2];
(async () => {
  fs.rmSync(SP + '/p11', {recursive: true, force: true});
  const P = await phone({port: 9440, prof: SP + '/p11'});
  const {ev, cap, tap, smooth} = P;
  await ev(`document.getElementById('gsSplash') && document.getElementById('gsSplash').remove(); db.limitMin = 0; db.auto = false; save(); go('feed')`); await sleep(800);
  console.log(await P.pretend()); await sleep(4500);
  console.log(await P.audit());
  const F = `document.getElementById('feed')`, S = `document.getElementById('sheetIn')`;
  const bib = `[...${F}.children].findIndex(s => s.querySelector('.bnav'))`;
  const card = `${F}.children[${bib}]`;
  const btnIn = (scope, t) => `[...${scope}.querySelectorAll('button')].find(b => b.textContent.trim().startsWith('${t}'))`;
  const book = t => `[...${S}.querySelectorAll('.bgrid:not(.ch) button')].find(b => b.firstChild.textContent.trim() === '${t}')`;
  const chap = n => `[...${S}.querySelectorAll('.bgrid.ch button')].find(b => b.textContent.trim() === '${n}')`;
  const sheetTo = sel => smooth(`const e = ${sel}; e && ${S}.scrollTo({top: e.offsetTop - 220, behavior: 'smooth'})`, 1200);
  await ev(`${F}.scrollTop = 0; 1`); await sleep(800);
  await P.start();
  cap('Listen to the Bible: a chapter every day'); await smooth(`${F}.scrollTo({top: ${card}.offsetTop, behavior: 'smooth'})`, 1900); await sleep(600);
  cap('Tap ▶ to listen, read by jw.org'); await tap(`${card}.querySelector('.lplay')`, `layerToggle(${card}.querySelector('.card[data-id]').dataset.id)`); await sleep(3000);
  await ev(`layerStop(); 1`); await sleep(400);
  cap('◀ ▶ go to the previous or next chapter'); await tap(`${card}.querySelector('.bnav button:last-child')`); await sleep(2600);
  await ev(`layerStop(); 1`); await tap(`${card}.querySelector('.bnav button:first-child')`); await sleep(2400); await ev(`layerStop(); 1`);
  cap('Tap the chapter name to pick a book'); await tap(`${card}.querySelector('.bname')`); await sleep(2200);
  cap('Started partway through a reading schedule?'); await sleep(900);
  await tap(btnIn(S, '✏️ Mark')); await sleep(1500);
  cap('Mark everything up to the last chapter you read'); await tap(btnIn(S, 'Everything up')); await sleep(1400);
  await sheetTo(book('Matthew')); await tap(book('Matthew')); await sleep(1500);
  await tap(chap('4')); await sleep(2600);
  await tap(btnIn(S, '✓ Done marking')); await sleep(900);
  cap('Green is read, blue is started'); await tap(btnIn(S, '← All books')); await sleep(1600);
  await sheetTo(book('Matthew')); await sleep(1600);
  cap('Your daily reading carries on from the next chapter'); await tap(book('Matthew')); await sleep(1600);
  await tap(chap('5')); await sleep(2800); await ev(`layerStop(); 1`);
  cap('On the Shelf: how many chapters a day'); await tap(`document.querySelector('nav button[data-v=library]')`, `go('library')`); await sleep(1000);
  await tap(btnIn(`document.getElementById('library')`, '📚 Shelf'), `go('shelf')`); await sleep(1500);
  const item = `[...document.querySelectorAll('#shelf .shelfitem')].find(b => b.textContent.includes('Listen to the Bible'))`;
  await smooth(`${item}.scrollIntoView({behavior: 'smooth', block: 'center'})`, 1200);
  await tap(item); await sleep(1500);
  await tap(`${S}.querySelectorAll('.step button')[1]`); await sleep(1500);
  await tap(btnIn(S, 'Done')); await sleep(700);
  cap('📖 Bible reading is in Treasures too'); await tap(`document.querySelector('nav button[data-v=library]')`, `go('library')`); await sleep(1300);
  await tap(btnIn(`document.getElementById('library')`, '📖 Bible'), `bibleMark=null;biblePicker()`); await sleep(2400);
  await ev(`bibleMark=null; closeSheet(); go('feed'); 1`); await sleep(1500);
  console.log(await P.audit());
  await P.stop('11-bible', {title: 'Bible reading', sub: 'Listen every day and see how far you’ve come', note: 'Sample cards stand in for jw.org content'});
  console.log('errors', P.errs.slice(0, 5)); P.close(); process.exit(0);
})().catch(e => { console.error(e); process.exit(1); });
